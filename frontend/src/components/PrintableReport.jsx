import { latestRevisions } from '../revisions';

// Rendered off-screen and shown only by the print stylesheet, so "Print or
// save report" produces a clean document through the browser's own PDF export.
export default function PrintableReport({ analysis, revisions, acknowledged }) {
  const { report, title } = analysis;
  const date = new Date().toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' });

  return (
    <article className="print-report">
      <header>
        <h1>Compliance report</h1>
        <p className="print-report__title">{title || 'Untitled manuscript'}</p>
        <p>
          {report.profile.name} · {date} · Score {report.score} / 100
        </p>
      </header>

      <section>
        <h2>Automated checks</h2>
        <table>
          <thead>
            <tr>
              <th>Check</th>
              <th>Expected</th>
              <th>Found</th>
              <th>Result</th>
            </tr>
          </thead>
          <tbody>
            {report.checks.map((check) => (
              <tr key={check.id}>
                <td>{check.label}</td>
                <td>{check.expected}</td>
                <td>{check.observed}</td>
                <td>{check.passed ? 'Pass' : 'Fail'}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>

      <section>
        <h2>Open issues</h2>
        {report.issues.length === 0 ? (
          <p>None.</p>
        ) : (
          <ol>
            {report.issues.map((issue) => (
              <li key={issue.id}>
                <strong>
                  {issue.severity} · {issue.section === 'document' ? 'whole paper' : issue.section}
                  {acknowledged.has(issue.id) ? ' · marked as done' : ''}
                </strong>
                <br />
                {issue.problem} {issue.action}
              </li>
            ))}
          </ol>
        )}
      </section>

      <section>
        <h2>Accepted revisions</h2>
        {revisions.length === 0 ? (
          <p>None.</p>
        ) : (
          latestRevisions(revisions).map((revision) => (
            <div key={revision.section} className="print-report__revision">
              <h3>{revision.section}</h3>
              {revision.changeSummary && <p><em>{revision.changeSummary}</em></p>}
              <h4>Original</h4>
              <p>{revision.originalText}</p>
              <h4>Revised</h4>
              <p>{revision.revisedText}</p>
            </div>
          ))
        )}
      </section>

      <section>
        <h2>Manual checklist</h2>
        <ul className="print-report__checklist">
          {report.manualChecks.map((item) => (
            <li key={item.title}>
              <strong>{item.title}.</strong> {item.rule}
            </li>
          ))}
        </ul>
      </section>

      <footer>
        Generated by Research Copilot. Checks are automated and cover text only. Revisions were proposed by
        Google Gemini and accepted individually by the author, who remains responsible for the manuscript.
      </footer>
    </article>
  );
}
